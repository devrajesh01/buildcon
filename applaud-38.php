                img: "assets/images/projects/spacius-right-image.jpg",
                title: "WHERE CALM LIVING\nMEETS THE CITY",
                desc: "From open interiors to thoughtfully planned common spaces. Features that balance the desire of your city living with the calm you need from a residential sanctuary."
            }
        ];

        let luxuryCurrent = 0;
        const luxuryTrack = document.getElementById('luxuryTrack');
        let autoSlideInterval;

        function startAutoSlide() {
            stopAutoSlide();
            autoSlideInterval = setInterval(() => {
                luxuryCurrent = (luxuryCurrent + 1) % luxurySlides.length;
                renderLuxurySlider();
            }, 5000);
        }

        function stopAutoSlide() {
            if (autoSlideInterval) clearInterval(autoSlideInterval);
        }

        function renderLuxurySlider() {
            const n = luxurySlides.length;
            const p = (luxuryCurrent - 1 + n) % n;
            const nx = (luxuryCurrent + 1) % n;
            luxuryTrack.innerHTML = '';

            [[p, 'side'], [luxuryCurrent, 'active'], [nx, 'side']].forEach(([idx, cls]) => {
                const s = luxurySlides[idx];
                const div = document.createElement('div');
                div.className = 'luxury-slide ' + cls;
                div.innerHTML = `
                    <div class="luxury-img-box">
                        <img src="${s.img}" alt="${s.title.replace('\n', ' ')}">
                    </div>
                    <div class="luxury-slide-content">
                        <h2>${s.title.replace('\n', '<br>')}</h2>
                        <p>${s.desc}</p>
                    </div>`;
                luxuryTrack.appendChild(div);
            });
        }

        document.getElementById('luxuryPrev').onclick = () => {
            luxuryCurrent = (luxuryCurrent - 1 + luxurySlides.length) % luxurySlides.length;
            renderLuxurySlider();
            startAutoSlide();
        };
        document.getElementById('luxuryNext').onclick = () => {
            luxuryCurrent = (luxuryCurrent + 1) % luxurySlides.length;
            renderLuxurySlider();
            startAutoSlide();
        };

        renderLuxurySlider();
        startAutoSlide();
    </script>
HTML;
